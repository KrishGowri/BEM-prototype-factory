def idf_object(object_type: str, fields: Iterable[object]) -> str:
    """Format an IDF object, preserving blank fields as empty strings."""
    values = ["" if value is None else str(value) for value in fields]
    lines = [f"{object_type},"]
    lines.extend(f"  {value}{';' if index == len(values) - 1 else ','}"
                 for index, value in enumerate(values))
    return "\n".join(lines)


def compact_schedule(name: str, kind: str, entries: list[tuple[str, str]]) -> str:
    fields: list[object] = [name, kind, "Through: 12/31"]
    for day, value in entries:
        fields.extend((f"For: {day}", "Until: 24:00", value))
    fields.append("For: AllOtherDays")
    fields.extend(("Until: 24:00", "0"))
    return idf_object("Schedule:Compact", fields)


def create_idf(config: dict) -> str:
    width = config["width"]
    depth = config["depth"]
    height = config["height"]
    floors = config["floors"]
    floor_area = width * depth * floors
    zone_height = height
    climate = CLIMATES[config["climate_zone"]]
    wall_area = 2 * (width + depth) * zone_height
    window_ratio = config["wwr"] / 100
    window_width_ratio = 0.7
    window_h = min(zone_height - 1.0,
                   max(0.5, wall_area * window_ratio / (2 * (width + depth) * window_width_ratio)))
    window_w = window_width_ratio
    parts: list[str] = [
        "! Generated by BEM Prototype Factory. Single-zone editable starter model.",
        f"! Prototype family selected: {config['family']} (selection is provenance only).",
        "! Review assumptions and assign a matching EPW before running EnergyPlus.",
        idf_object("Version", ["24.1"]),
        idf_object("SimulationControl", ["No", "No", "No", "Yes", "Yes"]),
        idf_object("Building", [config["name"], 0.04, "Suburbs", 0.004, 0.4, "FullExterior", 25, 6]),
        idf_object("Timestep", [6]),
        idf_object("GlobalGeometryRules", ["UpperLeftCorner", "Counterclockwise", "World", "Relative", "Relative"]),
        idf_object("Site:Location", [climate.city, climate.latitude, climate.longitude, climate.timezone, climate.elevation]),
        idf_object("RunPeriod", ["Annual", 1, 1, "", 12, 31, "", "Monday", "Yes", "Yes", "No", "Yes", "Yes"]),
        idf_object("Zone", ["Prototype Zone", 0, 0, 0, 1, 1, " autocalculate", " autocalculate", " autocalculate"]),
        idf_object("Material", ["Ext Wall Layer", "MediumRough", 0.20, 0.72, 1600, 840]),
        idf_object("Material", ["Roof Layer", "MediumRough", 0.18, 0.70, 1200, 900]),
        idf_object("Material", ["Slab Layer", "MediumRough", 0.15, 1.40, 2200, 900]),
        idf_object("Material", ["Interior Layer", "MediumSmooth", 0.10, 0.90, 800, 900]),
        idf_object("WindowMaterial:SimpleGlazingSystem", ["Prototype Glazing", 2.7, 0.40, 0.60]),
        idf_object("Construction", ["Exterior Wall", "Ext Wall Layer", "Interior Layer"]),
        idf_object("Construction", ["Roof", "Roof Layer", "Interior Layer"]),
        idf_object("Construction", ["Ground Floor", "Slab Layer", "Interior Layer"]),
        idf_object("Construction", ["Interior Partition", "Interior Layer"]),
        idf_object("Construction", ["Exterior Window", "Prototype Glazing"]),
        idf_object("ScheduleTypeLimits", ["Fraction", 0, 1, "CONTINUOUS", "DIMENSIONLESS"]),
        idf_object("ScheduleTypeLimits", ["Temperature", -60, 200, "CONTINUOUS", "TEMPERATURE"]),
        compact_schedule("Always On", "Fraction", [("AllDays", "1")]),
        compact_schedule("Occupancy", "Fraction", [("Weekdays", "1"), ("Weekends", "0.1"), ("Holidays", "0.1")]),
        compact_schedule("Lighting Availability", "Fraction", [("Weekdays", "1"), ("Weekends", "0.25"), ("Holidays", "0.1")]),
        compact_schedule("Equipment Availability", "Fraction", [("AllDays", "1")]),
        compact_schedule("Heating Setpoint", "Temperature", [("AllDays", str(config["heat_setpoint"]))]),
        compact_schedule("Cooling Setpoint", "Temperature", [("AllDays", str(config["cool_setpoint"]))]),
        idf_object("ZoneControl:Thermostat", ["Prototype Thermostat", "Prototype Zone", "Always On", "ThermostatSetpoint:DualSetpoint", "Prototype Dual Setpoint"]),
        idf_object("ThermostatSetpoint:DualSetpoint", ["Prototype Dual Setpoint", "Heating Setpoint", "Cooling Setpoint"]),
        idf_object("People", ["Prototype Occupants", "Prototype Zone", "Occupancy", "People/Area", "", config["people_density"], "", 0.3, "autocalculate", "Activity Level"]),
        compact_schedule("Activity Level", "Any Number", [("AllDays", "120")]),
        idf_object("Lights", ["Prototype Lighting", "Prototype Zone", "Lighting Availability", "Lighting Level", "", config["lighting_w_m2"], "", 0.2, 0.2, 0, "General", "General", "General"]),
        idf_object("ElectricEquipment", ["Prototype Equipment", "Prototype Zone", "Equipment Availability", "Equipment Level", "", config["equipment_w_m2"], "", 0.3, 0.2, 0, "General", "General"]),
        idf_object("ZoneInfiltration:DesignFlowRate", ["Prototype Infiltration", "Prototype Zone", "Always On", "Flow/ExteriorArea", "", "", config["infiltration"] / 3600, "", 0.0, 0.0, 0.0]),
        idf_object("ZoneAirContaminantBalance", ["No", "", "No", ""]),
    ]

    # One rectangular zone per floor is beyond this compact generator's scope;
    # floors scale internal loads and reporting area while geometry stays one zone.
    surfaces = [
        ("Floor", "Ground Floor", "Ground", "NoSun", "NoWind", [(0, depth, 0), (width, depth, 0), (width, 0, 0), (0, 0, 0)]),
        ("Roof", "Roof", "Outdoors", "SunExposed", "WindExposed", [(0, 0, zone_height), (width, 0, zone_height), (width, depth, zone_height), (0, depth, zone_height)]),
        ("Wall South", "Exterior Wall", "Outdoors", "SunExposed", "WindExposed", [(0, 0, 0), (width, 0, 0), (width, 0, zone_height), (0, 0, zone_height)]),
        ("Wall East", "Exterior Wall", "Outdoors", "SunExposed", "WindExposed", [(width, 0, 0), (width, depth, 0), (width, depth, zone_height), (width, 0, zone_height)]),
        ("Wall North", "Exterior Wall", "Outdoors", "SunExposed", "WindExposed", [(width, depth, 0), (0, depth, 0), (0, depth, zone_height), (width, depth, zone_height)]),
        ("Wall West", "Exterior Wall", "Outdoors", "SunExposed", "WindExposed", [(0, depth, 0), (0, 0, 0), (0, 0, zone_height), (0, depth, zone_height)]),
    ]
    for surface_name, construction, boundary, sun, wind, vertices in surfaces:
        fields: list[object] = [surface_name, "Floor" if surface_name == "Floor" else ("Roof" if surface_name == "Roof" else "Wall"), construction, "Prototype Zone", boundary, "", " autocalculate", sun, wind, len(vertices)]
        for vertex in vertices:
            fields.extend(vertex)
        parts.append(idf_object("BuildingSurface:Detailed", fields))

    # Four centered windows, sized from the requested gross-wall WWR.
    wall_dimensions = [("South", width, 0, 0, 0), ("East", depth, width, 0, 90),
                       ("North", width, width, depth, 180), ("West", depth, 0, depth, 270)]
    for direction, span, x0, y0, _rotation in wall_dimensions:
        w = min(span * 0.7, max(0.5, span * 0.7))
        h = min(zone_height - 1.0, wall_area * window_ratio / (4 * w)) if window_ratio else 0
        if h <= 0.05:
            continue
        x1 = x0 + (span - w) / 2
        y1 = y0 + (span - w) / 2
        z0 = max(0.5, (zone_height - h) / 2)
        z1 = min(zone_height - 0.5, z0 + h)
        if direction == "South": points = [(x1, 0, z0), (x1 + w, 0, z0), (x1 + w, 0, z1), (x1, 0, z1)]
        elif direction == "East": points = [(width, y1, z0), (width, y1 + w, z0), (width, y1 + w, z1), (width, y1, z1)]
        elif direction == "North": points = [(x1 + w, depth, z0), (x1, depth, z0), (x1, depth, z1), (x1 + w, depth, z1)]
        else: points = [(0, y1 + w, z0), (0, y1, z0), (0, y1, z1), (0, y1 + w, z1)]
        fields = [f"Window {direction}", "Window", "Exterior Window", f"Wall {direction}", "", "", "", 1, len(points)]
        for point in points:
            fields.extend(point)
        parts.append(idf_object("FenestrationSurface:Detailed", fields))

    # Ideal loads provides a simple, explicit zone-level HVAC system suitable
    # for early prototype comparisons, not detailed system/equipment studies.
    parts.extend([
        idf_object("ZoneHVAC:IdealLoadsAirSystem", ["Prototype Ideal Loads", "Always On", "Zone Supply Air Node", "", "", 50, 13, 0.015, 0.009, "LimitCapacity", "", "", "LimitCapacity", "", "", "", "", "None", 0.7, "None", "", "", "", "NoEconomizer", "None", 0, 0]),
        idf_object("ZoneHVAC:EquipmentList", ["Prototype Zone Equipment", "SequentialLoad", "ZoneHVAC:IdealLoadsAirSystem", "Prototype Ideal Loads", 1, 1]),
        idf_object("NodeList", ["Zone Inlet Nodes", "Zone Supply Air Node"]),
        idf_object("ZoneHVAC:EquipmentConnections", ["Prototype Zone", "Prototype Zone Equipment", "Zone Inlet Nodes", "", "Zone Air Node", ""]),
        idf_object("Output:Variable", ["*", "Zone Air Temperature", "Hourly"]),
        idf_object("Output:Variable", ["*", "Zone Ideal Loads Supply Air Total Heating Energy", "Hourly"]),
        idf_object("Output:Variable", ["*", "Zone Ideal Loads Supply Air Total Cooling Energy", "Hourly"]),
        idf_object("Output:Table:SummaryReports", ["AllSummary"]),
    ])
    return "\n\n".join(parts) + "\n"


st.set_page_config(page_title="BEM Prototype Factory", page_icon="🏢", layout="wide")
st.title("🏢 BEM Prototype Factory")
st.caption("Build an editable EnergyPlus starter model from common prototype-style assumptions.")
st.warning(
    "The CalBEM and DEER options label the requested prototype family, but this app does not bundle or reproduce official CalBEM/DEER model files. "
    "It generates a transparent, single-zone starter IDF with editable assumptions—not a code-compliant or calibrated prototype."
)

with st.sidebar:
    st.header("Prototype and building")
    family = st.selectbox("Prototype family", ["CalBEM", "DEER"])
    building_type = st.selectbox("Building type", list(BUILDING_DEFAULTS))
    climate_zone = st.selectbox("California Energy Commission climate zone", list(range(1, 17)), index=3)
    vintage = st.selectbox("Construction vintage (label only)", ["Pre-1980", "1980–2004", "2005–2013", "2014–present", "Custom"])
    name = st.text_input("Model name", f"{family}_{building_type.replace(' ', '_')}_CZ{climate_zone}")

base_people, base_lighting, base_equipment, base_infiltration, base_heat, base_cool = BUILDING_DEFAULTS[building_type]
st.subheader("Model characteristics")
left, right = st.columns(2)
with left:
    st.markdown("#### Geometry and envelope")
    width = st.number_input("Width (m)", min_value=5.0, max_value=200.0, value=30.0, step=1.0)
    depth = st.number_input("Depth (m)", min_value=5.0, max_value=200.0, value=20.0, step=1.0)
    floor_height = st.number_input("Story height (m)", min_value=2.4, max_value=8.0, value=3.5, step=0.1)
    floors = st.number_input("Number of stories (loads/area multiplier; generated geometry remains one story)", min_value=1, max_value=30, value=1, step=1)
    wwr = st.slider("Window-to-wall ratio (%)", min_value=0, max_value=60, value=30)
    st.caption("The current geometry generator models one floor/zone; stories multiply floor-area-dependent internal loads only.")
with right:
    st.markdown("#### Operation and HVAC")
    people_density = st.number_input("People density (people/m²)", min_value=0.0, max_value=2.0, value=base_people / 100, step=0.005, format="%.3f")
    lighting_w_m2 = st.number_input("Lighting power density (W/m²)", min_value=0.0, max_value=100.0, value=float(base_lighting), step=0.5)
    equipment_w_m2 = st.number_input("Equipment power density (W/m²)", min_value=0.0, max_value=200.0, value=float(base_equipment), step=0.5)
    infiltration = st.number_input("Infiltration (air changes per hour)", min_value=0.0, max_value=5.0, value=float(base_infiltration), step=0.01)
    heat_setpoint = st.number_input("Heating setpoint (°C)", min_value=10.0, max_value=26.0, value=float(base_heat), step=0.5)
    cool_setpoint = st.number_input("Cooling setpoint (°C)", min_value=18.0, max_value=35.0, value=float(base_cool), step=0.5)

if cool_setpoint <= heat_setpoint:
    st.error("Cooling setpoint must be higher than the heating setpoint.")
else:
    st.info(f"Site: {CLIMATES[climate_zone].city} · vintage: {vintage}. Site coordinates are representative defaults; use the EPW for your actual location.")
    config = {
        "family": family, "building_type": building_type, "climate_zone": climate_zone,
        "name": name, "width": width, "depth": depth, "height": floor_height,
        "floors": floors, "wwr": wwr, "people_density": people_density,
        "lighting_w_m2": lighting_w_m2, "equipment_w_m2": equipment_w_m2,
        "infiltration": infiltration, "heat_setpoint": heat_setpoint,
        "cool_setpoint": cool_setpoint,
    }
    idf = create_idf(config)
    st.subheader("Generated EnergyPlus input")
    st.caption("Review the assumptions and validate the exported IDF with the EnergyPlus version installed on your system.")
    st.download_button("Download IDF", data=idf, file_name=f"{name}.idf", mime="text/plain", type="primary")
    with st.expander("Preview IDF"):
        st.code(idf, language="text")

